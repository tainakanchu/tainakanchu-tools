/**
 * 航空会社の 2 レターコードを、リスト値('BR : EVA Air')に解決する。
 *
 * AI には 'BR' のようなコードだけを返させる(会社名まで正確に一致させるのは
 * 無理があり、'EVA Airways' のような表記揺れで必ず外れる)。突き合わせは
 * コード + ' : ' の前方一致で行い、リストに無ければ null を返す。
 * 近そうな候補で代用はしない。別の航空会社の便として登録されるほうが、
 * 空欄のまま人間に気付いてもらうより有害なため。
 */
export function resolveFlightCode(airlineCode: string): string | null {
  const prefix = `${airlineCode.trim().toUpperCase()} : `
  return FLIGHT_CODE_OPTIONS.find((code) => code.startsWith(prefix)) ?? null
}
