// ---------------------------------------------------------------------------
// 国籍に応じた Visa Type の切り替え
//
// テンプレートの M 列には次のデータ入力規則が張られている(sheet1.xml より):
//   INDIRECT( IF(I2="ROC,REPUBLIC OF CHINA(TAIWAN)", "TaiwanVisa",
//     IF(OR(I2="HKG,HONG KONG",I2="MAC,MACAO",I2="CHN,PEOPLE'S REPUBLIC OF CHINA"),
//        "ChinaVisa", "OtherVisa" )))
// つまり Visa Type の選択肢は国籍(I 列)で決まる。ここはその式を TypeScript に
// 写したもので、判定条件はテンプレートの式が唯一の根拠。
// ---------------------------------------------------------------------------

/** 国籍 = 台湾。Visa Type が VISA_TYPE_TAIWAN になる */
export const NATIONALITY_TAIWAN = 'ROC,REPUBLIC OF CHINA(TAIWAN)'

/** 国籍 = 香港・マカオ・中国。Visa Type が VISA_TYPE_CHINA になる */
export const NATIONALITIES_CHINA = [
  'HKG,HONG KONG',
  'MAC,MACAO',
  "CHN,PEOPLE'S REPUBLIC OF CHINA",
] as const

/** 国籍に対応する Visa Type の選択肢を返す */
export function visaTypeOptionsFor(nationality: string): ReadonlyArray<string> {
  if (nationality === NATIONALITY_TAIWAN) return VISA_TYPE_TAIWAN
  if (NATIONALITIES_CHINA.some((code) => code === nationality)) {
    return VISA_TYPE_CHINA
  }
  return VISA_TYPE_OTHER
}

/**
 * Visa Number(N 列)を書く必要があるか。
 *
 * 免簽證(ビザ免除)と未具入國許可(許可不要)には対応する番号が存在しない。
 * テンプレートの条件付き書式も、この 2 つのときだけ N 列を塗り分けている。
 * 番号の無い区分で入力欄を出すと「何を書けばいいのか」で必ず詰まるので、
 * UI 側はこの判定で欄ごと隠す。
 */
export function needsVisaNumber(visaType: string): boolean {
  return (
    visaType !== '免簽證 Visa-Exempt(include TAC)' &&
    visaType !== '未具入國許可 Permit-Exempt'
  )
}

