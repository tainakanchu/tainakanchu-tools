/**
 * TWAC(台湾オンライン入国カード)の公式サイトへの導線。
 *
 * ■ URL をここ 1 か所に集めてある理由
 *   このツールの出口は「書き出した Excel を公式サイトで取り込む」ことなので、
 *   公式サイトへのリンクは画面の複数箇所に出る。URL を書き写して増やすと、
 *   移民署がサイトを移したときに直し漏れが出る。**陳腐化したらここだけ直す。**
 *
 * ■ ディープパスにしない理由
 *   /nfoc/... のような下層 URL は改修のたびに変わる。ドメイン直下なら、
 *   中の導線が変わってもリンク切れにならない。入国前日にリンクが死んでいる
 *   のがいちばん困る種類のリンクなので、当たり続けることを優先する。
 *
 * ■ 偽サイトについて
 *   TWAC の登録は**無料**だが、これを有料で代行すると称する非公式サイトが
 *   実在し、移民署も注意喚起している。検索から入るとそちらに当たりうるので、
 *   このツールからは必ず公式ドメインへ直接飛ばし、画面にも
 *   「公式は immigration.gov.tw ドメインのみ」と書き添える(TWAC_SCAM_NOTE)。
 */

/** 台湾内政部移民署の TWAC 公式サイト(2026-08 時点で確認) */
export const TWAC_OFFICIAL_URL = 'https://twac.immigration.gov.tw'

/** 公式ドメイン。注意書きの文面と URL がズレないよう定数から組み立てる */
export const TWAC_OFFICIAL_DOMAIN = 'immigration.gov.tw'

/** リンクの近くに必ず添える一言 */
export const TWAC_SCAM_NOTE = `登録は無料です。有料の代行をうたう偽サイトがあるので、公式は ${TWAC_OFFICIAL_DOMAIN} ドメインのものだけだと覚えておいてください。`
