/**
 * 旅程上の並び順。「予約をどの順に読むか」を決める 1 か所。
 *
 * この計算は画面の日程タイムライン(derive.ts)と、場所の連続性の判定(itinerary.ts)の
 * 両方が必要とする。もとは同じ問題をそれぞれの都合で別々に解いていて、終日の予定を
 * 画面側は「表示タイムゾーンでのその日の 00:00」、判定側は「現地の 12:00 / 18:00」に
 * 置いていた。基準が 2 つあると、画面では「着いてから泊まる」順に見えているのに
 * 警告のほうは「泊まってから着く」前提で出る、という説明のつかない食い違いが起きる。
 * 並び順は旅程という 1 つの概念なので、決め方もここに集めておく。
 *
 * ■ 時刻付きの予定は epoch(絶対時刻)で並べる
 *   時差のある区間が混ざるので、現地の壁時計時刻で並べると
 *   「パリ 23:00 発の次が東京 07:00 着」のような逆転が起きる。
 *
 * ■ 素の epoch では並べられないものが 2 つある
 *   1 つは終日の予定。終日は現地 00:00 の ZonedDateTime として保存される
 *   (types.ts の Stamp 参照)。epoch そのままで並べると
 *   「9/6 からコペンハーゲンに泊まる」は 9/5 22:00 UTC、
 *   「9/6 12:20 デリー発コペンハーゲン行き」は 9/6 06:50 UTC になり、
 *   泊まる予定のほうが、そこへ向かう便より前に来てしまう。
 *   旅程の判定では、これで到着地の食い違いと出発地の食い違いが必ずペアで誤検出された。
 *
 *   もう 1 つは宿泊のチェックイン時刻。「16:00 チェックイン」は
 *   「16:00 から入れる」という意味であって「16:00 にそこにいる」ではないので、
 *   並び順の根拠にすると実態とずれる。利用者からの報告では
 *   「台北の宿 16:00 チェックイン」が「香港 18:50 発 台北 20:45 着」の便より前に並び、
 *   着く前に泊まる旅程に見えていた。時刻が入っているかどうかは、
 *   その宿がその夜を表しているという事実とは関係がない。
 *
 *   候補は 3 つあった。
 *   (a) 同一日なら「移動 → 滞在」の順に並べ替える
 *   (b) 「その日のみなしの時刻に始まる」とみなす ← これを採った
 *   (c) 区間として扱い、区間と点の重なりで判定する
 *   (a) は日付が主キーになるので、時差をまたいで現地日付が前後する区間
 *   (東京 6/12 23:00 発 → パリ 6/13 05:30 着)で並びが崩れる。
 *   (c) は「点の列」という前提で書かれた連続性の判定と宿の判定を両方作り直すことになり、
 *   壊す範囲が広すぎる。
 *   (b) は並び替えの鍵を作るこの 1 か所で閉じる。
 *
 * ■ みなしの時刻の決め方
 *   宿泊   … その日の終わり。終日か時刻付きかは問わない。「その日の最後に泊まる」と
 *            置けば、朝の便でも夜の便でも、日をまたぐ便(23:30 発 翌 06:00 着)でも、
 *            必ず「着いてから泊まる」の順になる。
 *            かつては終日の宿を 18:00 に置いていたが、それだと 20:15 発 21:50 着の
 *            夜の便より宿が先に来た。時刻付きの宿をチェックイン時刻のまま並べていた
 *            ときも同じことが起きた。どちらも「その日のいつ泊まるか」を当てにいって
 *            外している。当てにいかず、必ずその日の最後に置くほうが安定する。
 *
 *            「チェックインは翌日の朝 9 時のイベントとして扱う」案も出たが採らない。
 *            翌朝に置くと、翌日の早朝に発つ便(07:00 発など)より宿が後ろに回り、
 *            今度は「飛んでから泊まる」という逆向きの壊れ方をする。
 *            その夜を表す位置としては、その日の終わりで足りる。
 *   移動   … 12:00(終日の移動のみ)。その日のうちの移動は日中に済ませるものだから。
 *            「ミラノ→スイス」のように手段未定で終日の移動があると、同じ日の
 *            「時刻付きの到着便 → 終日の移動 → その晩の宿」を正しい順に並べる必要がある。
 *            移動と滞在を同じ時刻に寄せると、この 3 つの順序が決まらない。
 *   その他 … その日の始まり(終日のみ)。「6/12 は終日フリー」のような終日の予定は
 *            その日の見出しのように読まれるので、日付の先頭に置く。
 *            場所の入った終日のアクティビティが、その日の到着便より前に並ぶことで
 *            itinerary.ts の食い違いを誘う可能性は残る。それでも時刻で場合分けせず
 *            一律にその日の頭へ置くのは、あちらの方針が「見逃しより誤検出を許す」であり、
 *            「終日はその日の頭」という説明のほうが利用者に伝わるためである。
 *
 *   いずれもその予約自身のタイムゾーンでの時刻で、必ず startOfDay() を起点に組み立てる。
 *   夏時間の切替日にその日が 23 時間・25 時間になっても、みなしの時刻がその日から
 *   はみ出してはならない。
 *
 * ■ 宿泊でも実時刻のまま並べる 2 つの例外
 *   宿泊をその日の終わりに置く根拠は、その予約が「その夜」を表していることにある。
 *   その前提が成り立たない宿は、規則から外して実際の時刻で並べる。
 *
 *   (1) 泊まらない宿(デイユース)
 *       チェックアウトがチェックイン当日の宿は、数時間だけ部屋を取るだけで
 *       夜を表していない。その日の終わりへ送ると、実際には昼過ぎに出ているのに
 *       その日の最後の予定として読めてしまう。
 *   (2) 深夜のチェックイン
 *       深夜 02:00 に着いてそのまま入る宿は、暦の上では翌日でも実質は前夜の続きである
 *       (nights.ts の isLateNightCheckIn)。その日の終わりへ送ると、
 *       02:00 に入っているのにその日の昼の予定より後ろに並ぶ。
 *       ここは「その日の最後に泊まる」ではなく「その日の頭に入る」が実態なので、
 *       素の時刻がそのまま正しい位置になる。
 */

import { tryParseStamp } from './datetime'
import { isLateNightCheckIn } from './nights'
import type { Booking } from './types'

/** 終日の移動のみなしの開始時刻(その予約の現地の時) */
const ALL_DAY_MOVE_HOUR = 12

/**
 * チェックアウトがチェックイン当日か(= 夜を表していないデイユース)。
 * 判定はどちらもその予約自身の現地日付で行う。
 */
function isSameDayCheckOut(
  booking: Booking,
  start: Temporal.ZonedDateTime,
): boolean {
  if (booking.end === null) return false
  const end = tryParseStamp(booking.end)
  if (end === null) return false
  return end.toPlainDate().equals(start.toPlainDate())
}

/** その予約を「その日の終わり」に置くか。宿泊のうち、その夜を表しているものだけ */
function sleepsThatNight(
  booking: Booking,
  start: Temporal.ZonedDateTime,
): boolean {
  if (booking.kind !== 'lodging') return false
  if (isLateNightCheckIn(booking.start)) return false
  return !isSameDayCheckOut(booking, start)
}

/**
 * 並び替えに使う瞬間。宿泊と終日の予定は、その予約自身の現地のみなしの時刻に寄せる。
 *
 * start は booking.start をパースした結果を渡してもらう。呼び出し側は
 * 壊れた Stamp の扱い(除外するのか末尾に回すのか)をそれぞれ決めているので、
 * ここではパースに成功した予約だけを受け取る。
 *
 * isMove は「連続性の判定で移動として扱うか」(itinerary.ts の isMoveBooking)。
 * 種別が移動系でなくても出発地と到着地が入っていれば移動なので、
 * kind だけでは決められない。
 */
export function sortEpochOf(
  booking: Booking,
  start: Temporal.ZonedDateTime,
  isMove: boolean,
): number {
  const dayStart = start.startOfDay()
  // 宿泊はその日の終わり(翌日の始まりの 1ms 前)。datetime.ts の stampToEndEpoch と同じ形
  if (sleepsThatNight(booking, start))
    return dayStart.add({ days: 1 }).epochMilliseconds - 1

  if (!booking.start.allDay) return start.epochMilliseconds

  if (isMove)
    return dayStart.add({ hours: ALL_DAY_MOVE_HOUR }).epochMilliseconds
  return dayStart.epochMilliseconds
}
